// Настройки прототипа поиска (шаг 12, ADR-0048): веса полей и совпадений текстовой части, правила
// опечаток как в Meilisearch, служебные слова, оттенки кожи Fluent, доля смысловой части и длина
// вектора каждой модели, порт страницы поиска. Веса не подгоняются по эталону — подбирается только α.

/** Поле документа для текстовой части: имя, теги автора, синонимы ru/en (ADR-0048). */
export type Field = "name" | "tags" | "synonyms";

export const FIELDS: readonly Field[] = ["name", "tags", "synonyms"];

/** Вес поля: слово в имени весит больше, чем в тегах, а в тегах — больше, чем в синонимах. */
export const FIELD_WEIGHTS: Record<Field, number> = {
  name: 1,
  tags: 0.85,
  synonyms: 0.7,
};

export type MatchKind = "exact" | "prefix" | "typo1" | "typo2";

/** Качество совпадения слова запроса со словом документа: опечатка снижает оценку. */
export const MATCH_QUALITY: Record<MatchKind, number> = {
  exact: 1,
  prefix: 0.75,
  typo1: 0.5,
  typo2: 0.3,
};

/**
 * Опечатки — как в Meilisearch по умолчанию: одна у слов от 5 букв, две — от 9; опечатка в первой
 * букве считается за две (документация Meilisearch, typo tolerance).
 */
export const TYPO_MIN_LENGTH = { one: 5, two: 9 } as const;

/** Последнее слово запроса — ещё и как начало слова, если в нём хотя бы 2 буквы. */
export const PREFIX_MIN_LENGTH = 2;

/** Слов словаря на одно начало слова: самые короткие, то есть ближайшие к запросу. */
