/**
 * Нормировка смысловой части: место косинуса между 1-м и этим по счёту результатом запроса. Так у
 * трёх моделей одна шкала, хотя медиана косинуса у Gemini 0,66, а у OpenAI 0,34.
 */
export const VECTOR_NORM_RANK = 100;

export interface ModelSearch {
  /** Доля смысловой части в гибриде (ADR-0027): 0 — только текст, 1 — только смысл. */
  alpha: number;
  /** Длина вектора: первые числа, снова приведённые к длине 1 (ADR-0047). */
  length: number;
}

