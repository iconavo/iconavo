// Контроль качества (ADR-0016): размеры рисунка и пороги. Пороги уточняются после прогонов на
// настоящих данных — любое изменение записывается в ADR-0016.

/** Сетка набора рисуется в 64 px: у сетки 24 это 2,67 px на единицу, у сетки 32 — 2 px. */
export const RENDER_SIZE = 64;

/** Запас вокруг холста — четверть сетки, ровно 16 px: так видно, что рисунок вышел за край. */
export const MARGIN = RENDER_SIZE / 4;

/** Пустая: закрашено меньше 0,05% холста — меньше двух пикселей. Останавливает набор. */
export const EMPTY_LIMIT = 0.0005;

/** Почти пустая: закрашено меньше 0,5% холста (порог ADR-0016) — только отчёт. */
export const SPARSE_LIMIT = 0.005;

/** Обрезанная: рисунок выходит за холст больше чем на 2% размера — только отчёт. */
export const CROP_LIMIT = 0.02;

/** Пиксель за краем холста считается закрашенным, если он непрозрачен хотя бы на четверть. */
export const CROP_ALPHA = 64;

/** Иконка изменилась (или отличается от оригинала), если отличается больше 1% пикселей. */
export const CHANGED_PIXELS = 0.01;

/** Без новой версии источника изменилось или пропало больше 2% имён набора — «СТОП». */
export const CHANGED_NAMES_LIMIT = 0.02;

/** Чувствительность pixelmatch к разнице цвета: 0 — любая разница, 1 — никакая (у него 0,1). */
export const PIXELMATCH_THRESHOLD = 0.1;

/** Сколько карточек одного вида на набор показывает отчёт; дальше — «… и ещё N». */
export const REPORT_LIMIT = 500;
