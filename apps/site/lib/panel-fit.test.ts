import { describe, expect, it } from "vitest";
import { panelFit, panelWhole } from "./panel-fit";

describe("высота панели иконки — по месту в окне", () => {
  it("страница не прокручена: от верха панели до низа окна с отступом", () => {
    // Окно 900 px, панель начинается на 373 px, отступ 16 px.
    expect(panelFit(900, 373, 16)).toBe(511);
  });

  it("панель прилипла к верху: окно без двух отступов", () => {
    expect(panelFit(900, 16, 16)).toBe(868);
    // Выше отступа не бывает: верх считается по нему.
    expect(panelFit(900, -40, 16)).toBe(868);
  });

  it("внизу страницы: до конца места панели над подвалом, верх — у отступа", () => {
    // Место панели кончается на 834 px окна высотой 900: панель 16–834, а не выталкивается вверх.
    expect(panelFit(900, -34, 16, 240, 834)).toBe(818);
    expect(panelFit(900, 16, 16, 240, 834)).toBe(818);
    // Конец места ниже окна — как без него.
    expect(panelFit(900, 16, 16, 240, 2400)).toBe(868);
  });

  it("места совсем мало — не ниже предела", () => {
    expect(panelFit(900, 850, 16)).toBe(240);
    expect(panelFit(900, 850, 16, 300)).toBe(300);
  });
});

describe("колесо над панелью — крутит только её", () => {
  it("содержимое длиннее панели — прокручивается панель, страница стоит", () => {
    expect(panelWhole(1381, 802)).toBe(false);
    expect(panelWhole(870, 868)).toBe(false);
  });

  it("содержимое помещается целиком — прокручивать нечего, колесо крутит страницу", () => {
    expect(panelWhole(760, 868)).toBe(true);
    // Пиксель — на округление высоты.
    expect(panelWhole(869, 868)).toBe(true);
  });
});
